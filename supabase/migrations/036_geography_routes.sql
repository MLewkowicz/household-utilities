BEGIN;
CREATE TABLE ledger_private.geography_route_edges (a text NOT NULL,b text NOT NULL,PRIMARY KEY(a,b),CHECK(a<b));
CREATE TABLE ledger_private.geography_route_puzzles (id integer PRIMARY KEY, start text NOT NULL, finish text NOT NULL, minimum integer NOT NULL, solution jsonb NOT NULL);
CREATE TABLE ledger_private.geography_routes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),player text NOT NULL CHECK(player IN ('michal','rina','ohm','rohil')),day date NOT NULL,
 puzzle_id integer NOT NULL REFERENCES ledger_private.geography_route_puzzles(id),path jsonb NOT NULL,discovered jsonb NOT NULL,
 steps integer NOT NULL DEFAULT 0,mistakes integer NOT NULL DEFAULT 0,revision integer NOT NULL DEFAULT 0,
 complete boolean NOT NULL DEFAULT false,won boolean NOT NULL DEFAULT false,score integer NOT NULL DEFAULT 0,notice text NOT NULL DEFAULT '',
 UNIQUE(player,day)
);
ALTER TABLE ledger_private.geography_routes ENABLE ROW LEVEL SECURITY;
ALTER TABLE ledger_private.geography_route_edges ENABLE ROW LEVEL SECURITY;
ALTER TABLE ledger_private.geography_route_puzzles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ledger_private.geography_route_edges,ledger_private.geography_route_puzzles,ledger_private.geography_routes FROM PUBLIC,anon,authenticated;
CREATE FUNCTION public.utilities_geography_route_start(p jsonb) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE d date:=(now() AT TIME ZONE 'America/New_York')::date;slot integer;q ledger_private.geography_route_puzzles;a ledger_private.geography_routes;
BEGIN
 IF coalesce(p->>'player','') NOT IN ('michal','rina','ohm','rohil') THEN RAISE EXCEPTION 'Choose a household player for the daily trail';END IF;
 SELECT ((d-DATE '2026-11-09')%count(*)+count(*))%count(*) INTO slot FROM ledger_private.geography_route_puzzles;
 SELECT * INTO q FROM ledger_private.geography_route_puzzles WHERE id=slot;
 INSERT INTO ledger_private.geography_routes(player,day,puzzle_id,path,discovered) VALUES(p->>'player',d,q.id,jsonb_build_array(q.start),jsonb_build_array(q.start,q.finish)) ON CONFLICT(player,day) DO NOTHING;
 SELECT * INTO a FROM ledger_private.geography_routes WHERE player=p->>'player' AND day=d;
 RETURN to_jsonb(a);
END;$$;
CREATE FUNCTION public.utilities_geography_route_action(p jsonb) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE a ledger_private.geography_routes;q ledger_private.geography_route_puzzles;choice text:=p->>'choice';tail text;len integer;
BEGIN
 SELECT * INTO a FROM ledger_private.geography_routes WHERE id=(p->>'id')::uuid AND player=p->>'player' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Trail not found for this player';END IF;
 IF (p->>'revision')::integer IS NULL OR (p->>'revision')::integer>a.revision THEN RAISE EXCEPTION 'Refresh this trail before continuing';END IF;
 -- A retried action or an older tab gets the authoritative state without a second penalty.
 IF a.complete OR (p->>'revision')::integer<a.revision THEN RETURN to_jsonb(a);END IF;
 IF a.day<>(now() AT TIME ZONE 'America/New_York')::date THEN RAISE EXCEPTION 'A new daily trail is ready. Start today’s trail in settings';END IF;
 IF choice IS NULL OR (choice NOT IN ('back','give-up') AND NOT EXISTS(SELECT 1 FROM ledger_private.geography_catalog WHERE id=choice AND official)) THEN RAISE EXCEPTION 'Choose a country';END IF;
 len:=jsonb_array_length(a.path);tail:=a.path->>(len-1);SELECT * INTO q FROM ledger_private.geography_route_puzzles WHERE id=a.puzzle_id;
 IF choice=tail OR choice='back' AND len=1 THEN RETURN to_jsonb(a);END IF;
 IF choice='give-up' THEN a.complete:=true;a.notice:='revealed';
 ELSIF choice='back' THEN a.path:=a.path-(len-1);a.steps:=a.steps+1;a.notice:='back';
 ELSIF NOT EXISTS(SELECT 1 FROM ledger_private.geography_route_edges WHERE geography_route_edges.a=least(tail,choice) AND b=greatest(tail,choice)) THEN a.mistakes:=a.mistakes+1;a.notice:='not-neighbor';
 ELSE a.path:=a.path||jsonb_build_array(choice);IF NOT a.discovered ? choice THEN a.discovered:=a.discovered||jsonb_build_array(choice);END IF;a.steps:=a.steps+1;a.notice:='crossed';END IF;
 a.won:=a.path->>(jsonb_array_length(a.path)-1)=q.finish;a.complete:=a.complete OR a.won OR a.mistakes>=5;
 a.score:=CASE WHEN a.won THEN greatest(0,1000-100*greatest(0,a.steps-q.minimum)-100*a.mistakes) ELSE 0 END;a.revision:=a.revision+1;
 UPDATE ledger_private.geography_routes SET path=a.path,discovered=a.discovered,steps=a.steps,mistakes=a.mistakes,complete=a.complete,won=a.won,score=a.score,revision=a.revision,notice=a.notice WHERE id=a.id;
 RETURN to_jsonb(a);
END;$$;
CREATE FUNCTION public.utilities_geography_route_scores() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT coalesce(jsonb_agg(to_jsonb(s) ORDER BY s.score DESC,s.steps,s.mistakes,s.player),'[]'::jsonb) FROM (
 SELECT player,day,score,steps,mistakes,won FROM ledger_private.geography_routes WHERE complete AND day=(now() AT TIME ZONE 'America/New_York')::date) s;
$$;
CREATE FUNCTION public.utilities_geography_route_capabilities() RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path='' AS $$ SELECT '{"version":1,"puzzles":48}'::jsonb;$$;
REVOKE ALL ON FUNCTION public.utilities_geography_route_start(jsonb),public.utilities_geography_route_action(jsonb),public.utilities_geography_route_scores(),public.utilities_geography_route_capabilities() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.utilities_geography_route_start(jsonb),public.utilities_geography_route_action(jsonb),public.utilities_geography_route_scores(),public.utilities_geography_route_capabilities() TO anon,authenticated;
