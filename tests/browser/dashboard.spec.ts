import {test,expect} from '@playwright/test';
test('dark dashboard, monthly proration, and shared payment lifecycle',async({page,browser})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.emulateMedia({colorScheme:'dark'});await page.goto('/#utilities');await expect(page.getByText('Shared ledger · up to date')).toBeVisible();
 await expect(page.locator('.balance-card')).toHaveCount(4);
 await expect(page.locator('body')).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
 await page.getByRole('button',{name:'Rohil',exact:true}).click();
 const august=page.locator('#months>tr').filter({has:page.locator('.month-label',{hasText:'August'})});
 await expect(august).toContainText('$0.00');
 await page.getByRole('button',{name:'Show September details'}).click();
 await expect(page.locator('#details-2026-09')).toContainText('11 days split three ways. 17 days split four ways.');
 await page.getByRole('button',{name:'Household',exact:true}).click();
 const rinaCard=page.locator('.balance-card').filter({has:page.locator('.person-name',{hasText:'Rina'})});
 const initial=await rinaCard.locator('.balance-amount').textContent();
 await expect(rinaCard.locator('.balance-amount')).toHaveText('$126.77');
 await expect(page.locator('.balance-card.member-ohm .balance-amount')).toHaveText('$126.77');
 await page.locator('#new-payment').click();await page.locator('#payment-dialog').getByLabel('Who paid?').selectOption('rina');
 await page.getByLabel('Amount',{exact:true}).fill('13.37');await page.locator('#payment-dialog').getByText('Other',{exact:true}).click();
 await page.getByLabel('How did you pay?').fill('cash');await page.getByRole('button',{name:'Confirm payment',exact:true}).click();
 await expect(page.locator('#payment-dialog')).not.toBeVisible();
 await expect(page.locator('.payment-row')).toContainText('$13.37');
 await expect(rinaCard.locator('.balance-amount')).toHaveText('$113.40');
 const other=await browser.newPage();await other.goto('http://127.0.0.1:4174/#utilities');
 await expect(other.locator('.payment-row')).toContainText('$13.37');
 const row=page.locator('.payment-row').first();await expect(row.locator('.payment-actions')).toBeHidden();await expect(row.locator('.payment-method')).toBeHidden();
 await row.locator('summary.chore-corner-tab').click();await expect(row).toContainText('Paid by cash');
 await page.getByRole('button',{name:'Edit Rina payment of $13.37'}).click();
 await page.getByLabel('Amount',{exact:true}).fill('12.34');await page.locator('#payment-dialog').getByLabel('Changed by').selectOption('michal');
 await page.getByRole('button',{name:'Save changes'}).click();await expect(page.locator('#payment-dialog')).not.toBeVisible();
 await expect(page.locator('.payment-row')).toContainText('$12.34');
 await expect(rinaCard.locator('.balance-amount')).toHaveText('$114.43');
 await expect(row.locator('.payment-details')).toHaveAttribute('open','');await page.getByRole('button',{name:'Delete Rina payment of $12.34'}).click();
 await page.getByRole('button',{name:'Delete payment',exact:true}).click();
 await expect(page.locator('#delete-dialog')).not.toBeVisible();await expect(rinaCard.locator('.balance-amount')).toHaveText(initial!);
 await page.locator('#show-deleted-payments').check();await expect(page.locator('.payment-row').first()).toContainText('DELETED');await expect(page.locator('.history-group')).toHaveCount(0);
 const exported=await page.request.post('/rest/v1/rpc/utilities_dashboard',{headers:{apikey:'local-public'},data:{}});expect((await exported.json()).history).toHaveLength(3);
 await other.close();expect(errors).toEqual([]);
});
test('mobile layout and unavailable backend preserve a clearly labeled snapshot',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/#utilities');
 await expect(page.locator('.balance-card')).toHaveCount(4);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.route('**/rest/v1/rpc/**',route=>route.abort());await page.reload();
 await expect(page.getByText('Viewing saved snapshot')).toBeVisible();
 await expect(page.locator('#new-payment')).toBeDisabled();await expect(page.locator('#notice')).toContainText('Payment entry is disabled');
 await expect(page.locator('.balance-card')).toHaveCount(4);
});
